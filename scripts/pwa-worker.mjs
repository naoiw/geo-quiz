import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

function listFiles(root, directory = "") {
  return readdirSync(join(root, directory), { withFileTypes: true }).flatMap((entry) => {
    const relative = directory ? directory + "/" + entry.name : entry.name;
    return entry.isDirectory() ? listFiles(root, relative) : [relative];
  });
}

/** Generate a self-contained, versioned offline worker for the actual Vite build output. */
export function buildServiceWorker(distDir) {
  const files = listFiles(distDir).filter((path) =>
    path !== "sw.js" && !path.split("/").some((component) => component.startsWith("."))).sort();
  if (!files.includes("index.html") || !files.includes("manifest.webmanifest")) {
    throw new Error("PWA build requires index.html and manifest.webmanifest.");
  }
  const checksum = createHash("sha256");
  for (const file of files) {
    checksum.update(file);
    checksum.update("\0");
    checksum.update(readFileSync(join(distDir, file)));
  }
  const cacheName = "geo-quiz-" + checksum.digest("hex").slice(0, 16);
  const precache = ["./", ...files.map((file) => "./" + file)];
  const content = `// Generated by scripts/build-service-worker.mjs. Do not edit dist/sw.js.
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(precache)};
const OFFLINE_ENTRY = new URL("./index.html", self.registration.scope).href;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((name) => name.startsWith("geo-quiz-") && name !== CACHE_NAME)
      .map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const url = new URL(event.request.url);
  const scope = new URL(self.registration.scope);
  if (url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) return;

  if (event.request.mode === "navigate") {
    event.respondWith(fetch(event.request).catch(async () => {
      const cached = await caches.match(OFFLINE_ENTRY);
      return cached ?? Response.error();
    }));
    return;
  }
  event.respondWith(caches.match(event.request).then((cached) => cached ?? fetch(event.request)));
});
`;
  writeFileSync(join(distDir, "sw.js"), content);
  return { cacheName, files };
}
